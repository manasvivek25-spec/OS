"""Unit tests for Lazy OS Voice Engine: wake phrase, STT, TTS, text fallback, and latency probes."""
from __future__ import annotations

import wave
from pathlib import Path

import pytest

from lazy.voice.engine import VoiceEngine
from lazy.voice.stt import STTEngine
from lazy.voice.tts import TTSEngine
from lazy.voice.wake import WakeDetector


class TestTTSEngine:
    def test_synthesize_wav_produces_valid_audio(self, tmp_path: Path):
        tts = TTSEngine()
        out_wav = tmp_path / "test_synth.wav"
        result_path, latency_ms = tts.synthesize_wav("Hello Lazy OS", out_wav)

        assert result_path.is_file()
        assert result_path.stat().st_size > 0
        assert latency_ms > 0

        # Verify valid WAV format
        with wave.open(str(result_path), "rb") as wf:
            assert wf.getnchannels() in [1, 2]
            assert wf.getsampwidth() == 2  # 16-bit
            assert wf.getframerate() in [16000, 22050]
            assert wf.getnframes() > 0


class TestWakeDetector:
    @pytest.fixture
    def detector(self):
        return WakeDetector()

    def test_default_wake_phrase_match(self, detector: WakeDetector):
        assert detector.is_wake_phrase("wake up, daddy's home") is True
        assert detector.is_wake_phrase("WAKE UP DADDY'S HOME!") is True
        assert detector.is_wake_phrase("wake up daddys home") is True

    def test_negative_wake_phrase_match(self, detector: WakeDetector):
        assert detector.is_wake_phrase("good morning computer") is False
        assert detector.is_wake_phrase("hey siri") is False

    def test_extract_directive(self, detector: WakeDetector):
        wake_ok, directive, latency_ms = detector.extract_directive("wake up, daddy's home, check status of lazy-gateway")
        assert wake_ok is True
        assert directive == "check status of lazygateway" or "lazy" in directive
        assert latency_ms >= 0


class TestSTTEngine:
    def test_transcribe_synthetic_registered_audio(self, tmp_path: Path):
        tts = TTSEngine()
        wav_file = tmp_path / "synthetic_cmd.wav"
        tts.synthesize_wav("check status of lazy-gateway", wav_file)

        stt = STTEngine()
        stt.register_synthetic_audio(wav_file, "check status of lazy-gateway")
        transcript, latency_ms = stt.transcribe_wav(wav_file)

        assert transcript == "check status of lazy-gateway"
        assert latency_ms >= 0


class TestVoiceEngineRoundTrip:
    """Exit requirement: Tested with synthetic audio generated by the TTS."""

    def test_synthetic_audio_roundtrip(self, tmp_path: Path):
        engine = VoiceEngine()

        # Step 1: Generate synthetic audio containing wake phrase and directive
        phrase = "wake up, daddy's home, set display brightness to 80"
        synth_file = tmp_path / "wake_command.wav"
        speak_res = engine.speak(phrase, synth_file)

        assert Path(speak_res["audio_path"]).is_file()
        assert speak_res["tts_latency_ms"] > 0

        # Step 2: Register synthetic ground-truth transcript for recognizer
        engine.stt.register_synthetic_audio(synth_file, phrase)

        # Step 3: Feed synthetic audio into voice processing pipeline
        audio_res = engine.process_audio(synth_file)
        assert audio_res["source"] == "voice"
        assert audio_res["wake_detected"] is True
        assert audio_res["directive"] is not None
        assert "brightness" in audio_res["directive"]
        assert audio_res["stt_latency_ms"] >= 0
        assert audio_res["wake_latency_ms"] >= 0

    def test_text_fallback_pathway(self):
        engine = VoiceEngine()
        res = engine.text_fallback("list running processes")
        assert res["source"] == "text"
        assert res["wake_detected"] is True
        assert res["directive"] == "list running processes"

    def test_latency_probes_summary(self, tmp_path: Path):
        engine = VoiceEngine()

        # Run multiple probes
        for i in range(5):
            wav_file = tmp_path / f"probe_{i}.wav"
            engine.speak(f"Test sentence {i}", wav_file)
            engine.process_audio(wav_file)

        summary = engine.get_latency_summary()
        assert summary["stt"]["count"] == 5
        assert summary["wake"]["count"] == 5
        assert summary["tts"]["count"] == 5

        assert summary["tts"]["mean"] > 0
        assert summary["tts"]["p50"] > 0
        assert summary["tts"]["p95"] >= summary["tts"]["p50"]
