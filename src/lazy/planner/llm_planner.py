"""LLM-backed planner implementation adhering to PlannerInterface.

Role B W3: Enhanced with GBNF grammar constraints, structured error handling,
and streaming support. No mock fallback.
"""
from __future__ import annotations

import json
from typing import Any, Dict, List, Optional

from lazy.llm.client import LLMClient
from lazy.llm.grammar import get_intent_gbnf
from lazy.planner.base import PlannerInterface


class LLMPlanner(PlannerInterface):
    """Planner client invoking grammar-constrained LLM inference.

    Uses GBNF grammar to force llama-server to output ONLY schema-valid
    JSON action plans conforming to lazy-policy tiers (L0–L4) and broker schemas.
    """

    def __init__(self, client: Optional[LLMClient] = None, **kwargs):
        self.client = client or LLMClient(**kwargs)
        self._grammar = get_intent_gbnf()

    def plan(
        self,
        user_input: str,
        requester: str = "text",
        task_id: Optional[str] = None,
        provenance: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Generate a single-step or multi-step plan using grammar-constrained LLM inference.

        The GBNF grammar ensures the LLM can only output valid Intent JSON
        with recognized capabilities from the 37-capability registry.
        """
        try:
            intent = self.client.generate_intent(
                user_input,
                grammar=self._grammar,
                requester=requester,
                task_id=task_id,
            )
            if provenance:
                intent["provenance"] = provenance
            return self.create_plan([intent], f"Plan generated by LLM for: '{user_input}'")
        except RuntimeError as e:
            # Return a structured error plan rather than crashing
            error_info = str(e)
            try:
                error_data = json.loads(error_info)
                reason = error_data.get("reason", error_info)
            except (json.JSONDecodeError, TypeError):
                reason = error_info

            error_intent = self.create_intent(
                capability="fs.read",
                params={"path": "/etc/issue"},
                requester=requester,
                task_id=task_id,
                provenance=[
                    {
                        "source": "planner",
                        "trusted": False,
                        "detail": f"LLM inference error: {reason}",
                    }
                ],
            )
            return self.create_plan(
                [error_intent],
                f"Error plan — LLM unavailable: {reason}",
            )

    def plan_streaming(
        self,
        user_input: str,
        requester: str = "text",
        task_id: Optional[str] = None,
    ):
        """Generator that yields token chunks during plan generation.

        Yields dicts with 'chunk', 'index', and 'done' fields for real-time
        WebSocket streaming to the HUD.
        """
        for chunk in self.client.generate_intent_streaming(
            user_input,
            grammar=self._grammar,
            requester=requester,
            task_id=task_id,
        ):
            yield chunk

    def propose_intent(
        self,
        capability: str,
        params: Dict[str, Any],
        requester: str = "text",
        task_id: Optional[str] = None,
        provenance: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Propose intent using factory."""
        return self.create_intent(
            capability, params, requester=requester, task_id=task_id, provenance=provenance
        )
