"""LLM-backed planner implementation adhering to PlannerInterface."""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from lazy.llm.client import LLMClient
from lazy.planner.base import PlannerInterface


class LLMPlanner(PlannerInterface):
    """Planner client invoking grammar-constrained LLM inference."""

    def __init__(self, client: Optional[LLMClient] = None, **kwargs):
        self.client = client or LLMClient(**kwargs)

    def plan(
        self,
        user_input: str,
        requester: str = "text",
        task_id: Optional[str] = None,
        provenance: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Generate a single-step or multi-step plan using grammar-constrained LLM inference."""
        intent = self.client.generate_intent(user_input, requester=requester, task_id=task_id)
        if provenance:
            intent["provenance"] = provenance
        return self.create_plan([intent], f"Plan generated by LLM for: '{user_input}'")

    def propose_intent(
        self,
        capability: str,
        params: Dict[str, Any],
        requester: str = "text",
        task_id: Optional[str] = None,
        provenance: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Propose intent using factory."""
        return self.create_intent(capability, params, requester=requester, task_id=task_id, provenance=provenance)
